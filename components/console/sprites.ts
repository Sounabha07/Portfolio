export type SpritePixel = { x: number; y: number; fill: string; cls?: "eye" | "lgt" };

const cache = new Map<SpriteKey, SpritePixel[]>();

/** Pixel list for an SVG sprite, in the same order the reference emits rects. */
export function spritePixels(k: SpriteKey): SpritePixel[] {
  const hit = cache.get(k);
  if (hit) return hit;
  const out: SpritePixel[] = [];
  SPRITES[k].forEach((row, y) =>
    [...row].forEach((ch, x) => {
      if (ch === ".") return;
      if (ch === "4") out.push({ x, y, fill: "var(--s1)", cls: "eye" });
      else if (ch === "5") out.push({ x, y, fill: "var(--s2)", cls: "lgt" });
      else out.push({ x, y, fill: `var(--s${ch})` });
    }),
  );
  cache.set(k, out);
  return out;
}
